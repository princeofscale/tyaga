import { api, ApiError } from "./ApiClient";

/**
 * Выход из аккаунта: запрос на сервер, затем `onLoggedOut` (очистка данных на устройстве и возврат на экран входа).
 * Не зависит от состояния приложения: им пользуются и меню профиля, и панель «Не удалось открыть приложение».
 * Ответ 401 («сессия уже закончилась») — тоже выход: сервер и так не считает человека вошедшим, делать на нём нечего (R11-REQ06).
 * Любая другая ошибка (нет связи, 5xx) пробрасывается — вызывающий показывает её человеку, данные на устройстве не трогаются.
 */
export async function signOutAccount(onLoggedOut: () => void): Promise<void> {
  try {
    await api("/api/auth/logout", "POST", {});
  } catch (e) {
    if (!(e instanceof ApiError && e.status === 401)) throw e;
  }
  onLoggedOut();
}
