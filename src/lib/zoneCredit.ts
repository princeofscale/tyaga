/**
 * Пояснение к числу «зачтено зонам». Один подход засчитывается каждой зоне, которую он нагружает,
 * поэтому число может быть больше числа подходов. Оговорку «число больше» пишем только когда это правда:
 * на пустой неделе («0 / 80») или когда цели зон срезали сумму, она ввела бы в заблуждение.
 */
export function zoneCreditNote(credited: number, workingSets: number): string {
  if (credited <= 0) return "";
  const base = "Один подход засчитывается каждой зоне, которую он нагружает: жим — и груди, и трицепсу.";
  return credited > workingSets ? `${base} Поэтому число больше, чем подходов в записи.` : base;
}
