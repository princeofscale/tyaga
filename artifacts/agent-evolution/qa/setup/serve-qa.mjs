import assert from 'node:assert/strict';
import { createServer } from 'node:net';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, openSync, existsSync, readdirSync, realpathSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
import { randomUUID, createHash } from 'node:crypto';
const root = resolve(process.cwd());
assert.equal(root, '/Users/princeofscale/Desktop/gym/tyaga-agent-evolution');
assert.equal(realpathSync(root), root, 'QA root must not redirect to original');
const branch = spawnSync('git', ['branch', '--show-current'], { cwd: root, encoding: 'utf8' });
assert.equal(branch.status, 0); assert.equal(branch.stdout.trim(), 'agents/tyaga-30-rounds');
const qa = join(root, 'artifacts/agent-evolution/qa/setup');
const evidence = mkdtempSync(join(qa, 'server-8796-'));
const configPath = join(qa, 'wrangler.qa.json');
const config = JSON.parse(readFileSync(configPath, 'utf8'));
assert.equal(resolve(qa, config.main), join(root, 'server/index.ts'));
assert.equal(resolve(qa, config.assets.directory), join(root, 'dist/client'));
assert.equal(config.d1_databases[0].database_name, 'tyaga-agent-qa-setup');
assert.equal(config.d1_databases[0].database_id, '00000000-0000-4000-8000-000000008796');
assert.deepEqual(config.assets.run_worker_first, ['/api/*']);
assert.ok(existsSync(join(root, 'dist/client/index.html')), 'frozen built client is required; DO NOT BUILD');
const persist = join(root, '.wrangler/agent-evolution-qa', 'browser-' + randomUUID());
mkdirSync(persist, { recursive: true });
const wrangler = join(root, 'node_modules/wrangler/bin/wrangler.js');
const json = (name, value) => writeFileSync(join(evidence, name), JSON.stringify(value, null, 2) + '\n', { flag: 'wx' });
const free = () => new Promise((resolveFree) => {
  const socket = createServer();
  socket.once('error', error => resolveFree({ free: false, error: String(error), port: 8796, host: '127.0.0.1', at: new Date().toISOString() }));
  socket.listen({ host: '127.0.0.1', port: 8796, exclusive: true }, () => socket.close(() => resolveFree({ free: true, port: 8796, host: '127.0.0.1', at: new Date().toISOString() })));
});
const producerPaths = (dir) => readdirSync(join(root, dir), { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? producerPaths(dir + '/' + entry.name) : entry.isFile() ? [dir + '/' + entry.name] : []);
const producerDirs = ['src', 'server', 'drizzle', 'dist', 'db', 'scripts'];
const producerFiles = ['package.json', 'package-lock.json', 'tsconfig.json', 'vite.config.ts', 'drizzle.config.ts', 'wrangler.jsonc', 'wrangler.production.jsonc'];
const producers = () => [...producerDirs.flatMap(producerPaths), ...producerFiles].sort().map(path => ({ path, sha256: createHash('sha256').update(readFileSync(join(root, path))).digest('hex') }));
const qaInputPaths = ['tests/agent-qa-domain.test.ts', 'tests/agent-qa-migrations.test.ts', 'tests/e2e/agent-qa-baseline.spec.ts', 'artifacts/agent-evolution/qa/setup/playwright.qa.config.ts', 'artifacts/agent-evolution/qa/setup/serve-qa.mjs', 'artifacts/agent-evolution/qa/setup/wrangler.qa.json', 'artifacts/agent-evolution/qa/setup/tsconfig.qa.json'];
const qaInputs = () => qaInputPaths.map(path => ({ path, sha256: createHash('sha256').update(readFileSync(join(root, path))).digest('hex') }));
const qaBefore = qaInputs(); json('frozen-qa-inputs-before.json', qaBefore);
const frozenBefore = producers();
json('frozen-producers-before.json', frozenBefore);
const before = await free();
json('preflight-before-migrations.json', before);
assert.equal(before.free, true, '8796 occupied: STOP, never reuse/kill another process');
json('paths-and-owner.json', { root, configPath, persist, evidence, node: process.version, qaParentPid: process.pid });
const migration = spawnSync(process.execPath, [wrangler, 'd1', 'migrations', 'apply', 'DB', '--local', '--persist-to', persist, '--config', configPath], { cwd: root, encoding: 'utf8' });
writeFileSync(join(evidence, 'migrations.log'), `${migration.stdout ?? ''}\n${migration.stderr ?? ''}\n[exit code: ${migration.status}]\n`, { flag: 'wx' });
assert.equal(migration.status, 0, 'actual own D1 migration failed');
const prelaunch = await free();
json('preflight-immediately-before-launch.json', prelaunch);
assert.equal(prelaunch.free, true, '8796 occupied immediately before launch: STOP');
const log = openSync(join(evidence, 'server.log'), 'wx');
const child = spawn(process.execPath, [wrangler, 'dev', '--local', '--ip', '127.0.0.1', '--port', '8796', '--config', configPath, '--persist-to', persist], { cwd: root, stdio: ['ignore', log, log] });
json('owned-server.json', { pid: child.pid, command: 'node wrangler dev --local --ip 127.0.0.1 --port 8796', persist, evidence, lifecycle: 'Playwright webServer child; no persistence claim across agy invocation' });
console.log('QA8796 bounded server evidence: ' + evidence);
let stopping = false;
const stop = (signal) => { if (!stopping) { stopping = true; child.kill(signal); } };
process.on('SIGTERM', () => stop('SIGTERM'));
process.on('SIGINT', () => stop('SIGINT'));
child.on('error', error => { json('launch-error.json', { error: String(error) }); process.exitCode = 1; });
child.on('close', async (code, signal) => {
  const port = await free();
  const qaAfter = qaInputs(); json('frozen-qa-inputs-after.json', qaAfter);
  const qaInputsUnchanged = JSON.stringify(qaAfter) === JSON.stringify(qaBefore);
  const frozenAfter = producers(); json('frozen-producers-after.json', frozenAfter);
  const producersUnchanged = JSON.stringify(frozenAfter) === JSON.stringify(frozenBefore);
  json('owned-teardown.json', { code, signal, requestedByQa: stopping, port, producersUnchanged, producerFiles: frozenBefore.length, qaInputsUnchanged, qaInputFiles: qaBefore.length, at: new Date().toISOString() });
  process.exit(stopping && port.free && producersUnchanged && qaInputsUnchanged ? 0 : code || 1);
});
